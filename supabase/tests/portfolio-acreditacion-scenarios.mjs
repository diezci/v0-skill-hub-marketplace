// Synthetic evidence, real PostgreSQL permissions and publication boundaries.
export async function testAcreditacionPortfolio({ db, asRole, rpc, one, check, expectError, ids, legacyPortfolio }) {
  const { actors, company, works } = legacyPortfolio
  const personalPublic = async () => (await db.query('select * from public.portfolio_publico($1)', [actors.owner])).rows
  const personalOwn = async () => (await db.query('select * from public.mi_portfolio()')).rows
  const evidence = 'Factura REF-2026-114 y fotografías del antes y después disponibles para comprobación.'
  await asRole('authenticated', actors.owner)
  const companyRows = await rpc('empresa_portfolio')
  check(companyRows.some(p => !p.trabajo_id), 'Proyectos externos previos se conservan para el propietario')
  await asRole('anon')
  const initial = await rpc('empresa_perfil_publico', [company])
  check(initial.portfolio.every(p => p.trabajo_id), 'Los proyectos externos heredados quedan privados hasta acreditarse')
  await asRole('authenticated', actors.owner)
  const external = { titulo: 'Proyecto con evidencias', descripcion: 'Instalación completa y fotos del trabajo', evidencia_acreditacion: evidence, presupuesto: 2345.67 }
  const item = (await rpc('empresa_portfolio_guardar', [JSON.stringify(external), null])).id
  let state = (await rpc('mis_acreditaciones_portfolio', ['empresa'])).find(p => p.id === item)
  check(state.acreditacion === 'pendiente', 'Alta externa queda pendiente')
  check((await rpc('empresa_portfolio')).find(p => p.id === item).evidencia_acreditacion === evidence, 'Editor recupera su evidencia privada')
  await expectError(() => rpc('portfolio_acreditaciones_listar'), /Solo el equipo/, 'Empresa no puede acceder a cola administrativa')
  await expectError(() => db.query("update diime_private.portfolio_acreditaciones set estado='acreditado' where item_id=$1", [item]), /permission denied/, 'Propietario no se acredita por SQL directo')
  await asRole('authenticated', ids.platformAdmin)
  const queued = (await rpc('portfolio_acreditaciones_listar')).find(p => p.item_id === item)
  check(queued.evidencia_acreditacion === evidence && !Object.hasOwn(queued, 'presupuesto'), 'Diime puede revisar evidencias sin exponer presupuesto exacto')
  const decide = (entry, decision='acreditado') => rpc('portfolio_acreditacion_revisar', [entry.tipo, entry.item_id, entry.revision_id, decision, 'Referencia contrastada con documentación de prueba'])
  await decide(queued)
  await asRole('anon')
  const approved = (await rpc('empresa_perfil_publico', [company])).portfolio.find(p => p.id === item)
  check(approved?.titulo === external.titulo, 'Solo la acreditación publica el proyecto externo')
  check(!Object.hasOwn(approved, 'evidencia_acreditacion') && !Object.hasOwn(approved, 'presupuesto'), 'Perfil público no filtra evidencias ni importe')
  await asRole('authenticated', actors.owner)
  await rpc('empresa_portfolio_guardar', [JSON.stringify({ ...external, descripcion: 'Contenido cambiado después de revisar' }), item])
  check((await rpc('mis_acreditaciones_portfolio', ['empresa'])).find(p => p.id === item).acreditacion === 'pendiente', 'Editar contenido reinicia revisión')
  await asRole('authenticated', ids.platformAdmin)
  await expectError(() => decide(queued), /ha cambiado/, 'Una pestaña antigua no acredita una versión nueva')
  const current = (await rpc('portfolio_acreditaciones_listar')).find(p => p.item_id === item)
  await decide(current, 'requiere_informacion')
  await asRole('authenticated', actors.owner)
  check((await rpc('mis_acreditaciones_portfolio', ['empresa'])).find(p => p.id === item).nota_acreditacion.includes('Referencia'), 'Solicitante recibe la observación')
  await asRole('anon')
  check(!(await rpc('empresa_perfil_publico', [company])).portfolio.some(p => p.id === item), 'Información pendiente no se publica')
  await expectError(() => rpc('portfolio_acreditaciones_listar'), /permission denied/, 'Anon no enumera evidencias')
  // Personal portfolio uses the same policy, including direct Data API access.
  await asRole()
  await db.exec(`grant insert,update,delete on public.portfolio to authenticated;
    create policy portfolio_owner_insert_test on public.portfolio for insert to authenticated with check(profesional_id=auth.uid());
    create policy portfolio_owner_update_test on public.portfolio for update to authenticated using(profesional_id=auth.uid()) with check(profesional_id=auth.uid());`)
  await asRole('authenticated', actors.owner)
  const personal = (await one('insert into public.portfolio(profesional_id,titulo,descripcion,evidencia_acreditacion) values($1,$2,$3,$4) returning id', [actors.owner, 'Proyecto personal externo', 'Descripción verificable del trabajo', evidence])).id
  check((await personalOwn()).some(p => p.id === personal), 'Particular ve su proyecto pendiente')
  await asRole('anon')
  check(!(await personalPublic()).some(p => p.id === personal), 'RPC público personal oculta pendientes')
  check(!(await db.query('select id from public.portfolio where id=$1', [personal])).rows.length, 'RLS oculta pendientes incluso consultando tabla directa')
  await expectError(() => db.query('select evidencia_acreditacion from public.portfolio'), /permission denied/, 'Evidencia no es columna pública')
  await asRole('authenticated', ids.platformAdmin)
  const personalEntry = (await rpc('portfolio_acreditaciones_listar')).find(p => p.item_id === personal)
  await decide(personalEntry)
  await asRole('anon')
  check((await personalPublic()).some(p => p.id === personal), 'Particular acreditado aparece en RPC público')
  check((await db.query('select id from public.portfolio where id=$1', [personal])).rows.length === 1, 'RLS permite contenido ya acreditado')
  await asRole('authenticated', actors.owner)
  await db.query("update public.portfolio set evidencia_acreditacion='Referencia nueva que requiere comprobación' where id=$1", [personal])
  await asRole('anon')
  check(!(await personalPublic()).some(p => p.id === personal), 'Cambiar evidencia invalida acreditación personal')
  // Linked completed work needs no manual review, but cannot remain public if its completion changes.
  await asRole('authenticated', actors.owner)
  const linked = (await rpc('empresa_portfolio_guardar', [JSON.stringify({ ...external, trabajo_id: works.completed }), null])).id
  await asRole('anon')
  check((await rpc('empresa_perfil_publico', [company])).portfolio.some(p => p.id === linked), 'Contrato completado publica sin revisión manual')
  await asRole()
  await db.exec('set session_replication_role=replica')
  await db.query("update public.trabajos set estado='pendiente' where id=$1", [works.completed])
  await db.exec('set session_replication_role=origin')
  await asRole('anon')
  check(!(await rpc('empresa_perfil_publico', [company])).portfolio.some(p => p.id === linked), 'Estado completado se comprueba al publicar')
  await asRole()
  await db.query('update public.profiles set es_admin=true where id=$1', [actors.owner])
  await asRole('authenticated', actors.owner)
  const own = (await rpc('portfolio_acreditaciones_listar')).find(p => p.item_id === personal)
  await expectError(() => decide(own), /propios proyectos/, 'Ni un administrador acredita su propio proyecto')
  const ownCompany = (await rpc('portfolio_acreditaciones_listar')).find(p => p.item_id === item)
  await expectError(() => decide(ownCompany), /propios proyectos/, 'Administrador vinculado no acredita su empresa')
  await asRole()
  check((await one('select count(*)::int n from diime_private.portfolio_acreditaciones_historial')).n >= 3, 'Revisiones conservan historial separado de ediciones')
  for (const table of ['portfolio_acreditaciones','portfolio_acreditaciones_historial']) check((await one('select relrowsecurity from pg_class where oid=$1::regclass', [`diime_private.${table}`])).relrowsecurity, 'Tablas privadas conservan RLS')
}
