// Local PostgreSQL only; no Stripe API or account mutation.
export async function testCifCobrosEmpresa({ db, asRole, one, rpc, check, expectError, ids }) {
 const owner='84000000-0000-4000-8000-000000000001'
 const other='84000000-0000-4000-8000-000000000002'
 const account='acct_test_legal_reconciliation'
 await asRole()
 for (const [id,name] of [[owner,'owner'],[other,'other']]) {
  await db.query('insert into auth.users(id,email,email_confirmed_at) values($1,$2,now())',[id,`cif-cobros-${name}@example.test`])
  await db.query('insert into public.profiles(id,email,nombre) values($1,$2,$3)',[id,`cif-cobros-${name}@example.test`,name])
 }
 await asRole('authenticated',owner)
 const company=await rpc('vincular_mi_empresa',[null,'Cobros legal SL','B84000001','DOC','Administrador único',null,'Madrid'])
 const submit=()=>rpc('empresa_solicitar_verificacion',['documental','Representante','Administrador único','poder.pdf',Buffer.from('%PDF-test').toString('base64'),true])
 const last=async()=> (await rpc('empresa_verificaciones_listar')).find(v=>v.empresa_id===company)
 await submit()
 await asRole('authenticated',ids.platformAdmin)
 const first=await last()
 await rpc('empresa_revisar_verificacion',[company,'verificada','Identidad original acreditada',first.id])
 await asRole('service_role')
 await rpc('registrar_cuenta_stripe_empresa',[company,owner,account])
 await rpc('actualizar_estado_cuenta_stripe_empresa',[company,account,true,true,true,'[]'])
 await asRole()
 // Existing histories must be byte-for-byte unchanged by identity reconciliation.
 const histories=JSON.stringify((await db.query('select id,proveedor_stripe_account_id,empresa_proveedora_id from public.trabajos order by id')).rows)
 const fiscal=JSON.stringify((await db.query('select * from diime_private.trabajos_facturacion order by trabajo_id')).rows)
 const save=(next,prev)=>rpc('empresa_guardar_datos_legales',[company,owner,'Cobros legal SL',next,'',JSON.stringify({razonSocial:'Cobros legal SL',cif:prev,domicilio:''}),null])
 await asRole('service_role');await save('B84000002','B84000001')
 await asRole()
 let row=await one('select * from public.empresas where id=$1',[company])
 check(row.identidad_cobros_pendiente && row.cif_cobros_anterior==='B84000001','CIF cambiado con Stripe queda pendiente y conserva identidad anterior')
 check(row.estado_verificacion==='requiere_informacion','Cambio no habilita nuevos contratos')
 check((await one('select stripe_account_id from public.empresa_cuentas_stripe where empresa_id=$1',[company])).stripe_account_id===account,'Cambio no desvincula cuenta Stripe')
 await asRole('authenticated',owner)
 await expectError(()=>db.query('update public.empresas set identidad_cobros_pendiente=false where id=$1',[company]),/permission denied/,'Responsable no libera el bloqueo directamente')
 await expectError(()=>db.query("update public.empresas set cif_cobros_anterior='B99999999' where id=$1",[company]),/permission denied/,'Responsable no falsifica CIF de cobros anterior')
 await submit()
 await asRole('authenticated',ids.platformAdmin)
 let current=await last()
 check(current.identidad_cobros_pendiente && current.stripe_account_id===account && current.cif_cobros_anterior==='B84000001','Consola Diime recibe cuenta y CIFs para contraste')
 await expectError(()=>rpc('empresa_revisar_verificacion',[company,'verificada','Aprobación desde cliente antiguo',current.id]),/cuenta de cobros/,'RPC de aprobación antigua no evita conciliación')
 await expectError(()=>db.query("select diime_private.empresa_revisar_verificacion($1,'verificada','Aprobación privada directa',$2)",[company,current.id]),/cuenta de cobros/,'Helper privado tampoco permite saltar conciliación')
 check((await one("select count(*)::int n from pg_proc p join pg_namespace n on n.oid=p.pronamespace where p.proname='empresa_revisar_verificacion' and p.pronargs<>4")).n===0,'No quedan sobrecargas antiguas de aprobación sin control')
 const approve=(changes={})=>rpc('empresa_revisar_verificacion_con_cobros',[company,changes.revision??current.id,changes.cif??current.cif,changes.account??account,changes.confirm??true,changes.note??'He contrastado la documentación y el CIF en la cuenta vinculada.'])
 await expectError(()=>approve({confirm:false}),/Confirma/,'Confirmación explícita obligatoria')
 await expectError(()=>approve({note:'Visto'}),/evidencias/,'Revisión requiere nota de comprobaciones')
 await expectError(()=>approve({cif:'B84000001'}),/CIF ha cambiado/,'CIF obsoleto no puede conciliarse')
 await expectError(()=>approve({account:'acct_other'}),/cuenta de cobros ha cambiado/,'No concilia una cuenta distinta')
 await expectError(()=>approve({revision:first.id}),/solicitud ha cambiado/,'Expediente antiguo rechaza operación atómica')
 await asRole()
 check((await one('select identidad_cobros_pendiente from public.empresas where id=$1',[company])).identidad_cobros_pendiente,'Rechazo de expediente revierte desbloqueo previo')
 await asRole('authenticated',owner)
 await expectError(()=>approve(),/Solo el equipo/,'Responsable no se concilia a través del endpoint')
 await asRole('anon')
 await expectError(()=>approve(),/permission denied/,'Anon no accede a conciliación')
 await asRole('service_role')
 await rpc('actualizar_estado_cuenta_stripe_empresa',[company,account,true,true,true,'[]'])
 await asRole()
 check((await one('select identidad_cobros_pendiente from public.empresas where id=$1',[company])).identidad_cobros_pendiente,'Sincronizar estado Stripe no elimina revisión de CIF')
 await asRole('authenticated',ids.platformAdmin)
 await approve()
 await asRole()
 row=await one('select * from public.empresas where id=$1',[company])
 check(!row.identidad_cobros_pendiente && row.estado_verificacion==='verificada','Conciliación y acreditación se completan juntas')
 check((await one("select count(*)::int n from public.empresa_actividad where empresa_id=$1 and accion='Identidad de cobros comprobada' and actor_usuario_id=$2",[company,ids.platformAdmin])).n===1,'Comprobación conserva actor y evidencia en auditoría')
 check(JSON.stringify((await db.query('select id,proveedor_stripe_account_id,empresa_proveedora_id from public.trabajos order by id')).rows)===histories,'Conciliación no cambia destinos históricos')
 check(JSON.stringify((await db.query('select * from diime_private.trabajos_facturacion order by trabajo_id')).rows)===fiscal,'Conciliación conserva snapshots fiscales')
 await asRole('service_role');await save('B84000003','B84000002');await save('B84000004','B84000003')
 await asRole()
 row=await one('select * from public.empresas where id=$1',[company])
 check(row.identidad_cobros_pendiente && row.cif_cobros_anterior==='B84000002','Cambios sucesivos conservan último CIF conciliado')
 await asRole('authenticated',owner);await submit()
 await asRole('authenticated',ids.platformAdmin);current=await last()
 await asRole();await db.query('update public.profiles set es_admin=true where id=$1',[owner])
 await asRole('authenticated',owner)
 await expectError(()=>approve(),/propia empresa/,'Administrador vinculado tampoco concilia su empresa')
 await asRole('authenticated',other)
 const unlinked=await rpc('vincular_mi_empresa',[null,'Sin cuenta SL','B84000005','DOC','Administrador único',null,'Madrid'])
 await asRole('service_role')
 await rpc('empresa_guardar_datos_legales',[unlinked,other,'Sin cuenta SL','B84000006','',JSON.stringify({razonSocial:'Sin cuenta SL',cif:'B84000005',domicilio:''}),null])
 await asRole()
 check(!(await one('select identidad_cobros_pendiente from public.empresas where id=$1',[unlinked])).identidad_cobros_pendiente,'Sin cuenta vinculada no se impone conciliación innecesaria')
}
